$pngBytes = [System.IO.File]::ReadAllBytes((Resolve-Path "public/favicon.png"))
$stream = [System.IO.File]::OpenWrite((Join-Path (Get-Location) "public/app.ico"))
$bw = New-Object System.IO.BinaryWriter($stream)
$bw.Write([UInt16]0)
$bw.Write([UInt16]1)
$bw.Write([UInt16]1)
$bw.Write([Byte]48)
$bw.Write([Byte]48)
$bw.Write([Byte]0)
$bw.Write([Byte]0)
$bw.Write([UInt16]1)
$bw.Write([UInt16]32)
$bw.Write([UInt32]$pngBytes.Length)
$bw.Write([UInt32]22)
$bw.Write($pngBytes)
$bw.Close()
$stream.Close()
Write-Host "app.ico generated successfully"
